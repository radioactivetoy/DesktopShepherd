//! Translations: English (the text in the code), Spanish, Catalan, French, German, Italian and
//! Portuguese.
//!
//! Every text the person sees goes through `t("English text")`, which returns the text in the
//! chosen language (Settings > Language; "Automatic" follows Windows' display language). Texts
//! with values use `{}` placeholders filled in order by `tf`. A text missing from a table simply
//! shows in English. Month and day names come from `month_name` / `weekday_name`.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::OnceLock;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Es,
    Ca,
    Fr,
    De,
    It,
    Pt,
}

/// 0 = English, 1 = Spanish, 2 = Catalan, 3 = French, 4 = German, 5 = Italian, 6 = Portuguese
/// (the language in use now).
static LANG: AtomicU8 = AtomicU8::new(0);

/// The choices in Settings, in order: (setting value, name shown in its own language).
/// Saved values never change meaning: new languages are only ever added at the end.
pub const CHOICES: &[(u8, &str)] = &[
    (0, "Automatic (Windows)"),
    (1, "English"),
    (2, "Español"),
    (3, "Català"),
    (4, "Français"),
    (5, "Deutsch"),
    (6, "Italiano"),
    (7, "Português"),
];

/// Windows' display language for this user, as one of ours (English if none).
pub fn windows_lang() -> Lang {
    #[cfg(windows)]
    unsafe {
        use windows::Win32::Globalization::GetUserDefaultUILanguage;
        // The low 10 bits are the primary language: 0x0A Spanish, 0x03 Catalan, 0x0C French,
        // 0x07 German, 0x10 Italian, 0x16 Portuguese.
        match GetUserDefaultUILanguage() & 0x3FF {
            0x0A => return Lang::Es,
            0x03 => return Lang::Ca,
            0x0C => return Lang::Fr,
            0x07 => return Lang::De,
            0x10 => return Lang::It,
            0x16 => return Lang::Pt,
            _ => {}
        }
    }
    Lang::En
}

/// Applies the setting (0 = automatic, 1 = English, 2 = Spanish, 3 = Catalan, 4 = French,
/// 5 = German, 6 = Italian, 7 = Portuguese).
pub fn set_lang(setting: u8) {
    let l = match setting {
        1 => Lang::En,
        2 => Lang::Es,
        3 => Lang::Ca,
        4 => Lang::Fr,
        5 => Lang::De,
        6 => Lang::It,
        7 => Lang::Pt,
        _ => windows_lang(),
    };
    LANG.store(
        match l {
            Lang::En => 0,
            Lang::Es => 1,
            Lang::Ca => 2,
            Lang::Fr => 3,
            Lang::De => 4,
            Lang::It => 5,
            Lang::Pt => 6,
        },
        Ordering::Relaxed,
    );
}

pub fn lang() -> Lang {
    match LANG.load(Ordering::Relaxed) {
        1 => Lang::Es,
        2 => Lang::Ca,
        3 => Lang::Fr,
        4 => Lang::De,
        5 => Lang::It,
        6 => Lang::Pt,
        _ => Lang::En,
    }
}

type Map = HashMap<&'static str, &'static str>;

fn table(l: Lang) -> &'static Map {
    static ES_MAP: OnceLock<Map> = OnceLock::new();
    static CA_MAP: OnceLock<Map> = OnceLock::new();
    static FR_MAP: OnceLock<Map> = OnceLock::new();
    static DE_MAP: OnceLock<Map> = OnceLock::new();
    static IT_MAP: OnceLock<Map> = OnceLock::new();
    static PT_MAP: OnceLock<Map> = OnceLock::new();
    static EMPTY: OnceLock<Map> = OnceLock::new();
    match l {
        Lang::Es => ES_MAP.get_or_init(|| ES.iter().copied().collect()),
        Lang::Ca => CA_MAP.get_or_init(|| CA.iter().copied().collect()),
        Lang::Fr => FR_MAP.get_or_init(|| FR.iter().copied().collect()),
        Lang::De => DE_MAP.get_or_init(|| DE.iter().copied().collect()),
        Lang::It => IT_MAP.get_or_init(|| IT.iter().copied().collect()),
        Lang::Pt => PT_MAP.get_or_init(|| PT.iter().copied().collect()),
        Lang::En => EMPTY.get_or_init(HashMap::new),
    }
}

/// The text in the language in use (the English text if it has no translation).
pub fn t(s: &'static str) -> &'static str {
    match lang() {
        Lang::En => s,
        l => table(l).get(s).copied().unwrap_or(s),
    }
}

/// `t` with `{}` placeholders filled in order: tf("{} items", &[&n]).
pub fn tf(s: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = String::new();
    let mut rest = t(s);
    for a in args {
        match rest.find("{}") {
            Some(i) => {
                out.push_str(&rest[..i]);
                out.push_str(&a.to_string());
                rest = &rest[i + 2..];
            }
            None => break,
        }
    }
    out.push_str(rest);
    out
}

