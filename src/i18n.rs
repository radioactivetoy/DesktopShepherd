/// "Sunday, 22 November" / "domingo, 22 de noviembre" / "diumenge, 22 de novembre" /
/// "dimanche 22 novembre" / "Sonntag, 22. November" / "domenica 22 novembre".
pub fn long_date(d: chrono::NaiveDate) -> String {
    use chrono::Datelike;
    let wd = weekday_name(d.weekday().num_days_from_monday());
    match lang() {
        Lang::Fr | Lang::It => format!("{wd} {}", day_month(d)),
        _ => format!("{wd}, {}", day_month(d)),
    }
}

/// "22 November" / "22 de noviembre" / "22 de novembre" / "22 novembre" / "22. November" (no weekday).
pub fn day_month(d: chrono::NaiveDate) -> String {
    use chrono::Datelike;
    let m = month_name(d.month());
    match lang() {
        Lang::En | Lang::It => format!("{} {m}", d.day()),
        Lang::Fr => {
            if d.day() == 1 {
                format!("1er {m}")
            } else {
                format!("{} {m}", d.day())
            }
        }
        Lang::De => format!("{}. {m}", d.day()),
        Lang::Es | Lang::Ca | Lang::Pt => {
            let de = if lang() == Lang::Ca && matches!(m.chars().next(), Some('a' | 'o')) { "d'" } else { "de " };
            format!("{} {de}{m}", d.day())
        }
    }
}

/// "November 2026" / "noviembre de 2026" / "novembre de 2026" / "novembre 2026".
pub fn month_year(d: chrono::NaiveDate) -> String {
    use chrono::Datelike;
    let m = month_name(d.month());
    match lang() {
        Lang::En | Lang::Fr | Lang::De | Lang::It => format!("{m} {}", d.year()),
        Lang::Es | Lang::Ca | Lang::Pt => format!("{m} de {}", d.year()),
    }
}

/// "22 Nov" / "22 nov" / "22. Nov".
pub fn short_date(d: chrono::NaiveDate) -> String {
    use chrono::Datelike;
    match lang() {
        Lang::De => format!("{}. {}", d.day(), month_short(d.month())),
        _ => format!("{} {}", d.day(), month_short(d.month())),
    }
}

